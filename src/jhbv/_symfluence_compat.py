__all__ = sorted(_NAMES)


def _import_first_available(canonical: str, legacy: str) -> Any:
    try:
        return import_module(canonical)
    except ModuleNotFoundError as exc:
        # Fall back only when the canonical module itself is absent (an older
        # symfluence); a missing third-party dependency must still surface.
        missing = exc.name or ""
        if not (canonical == missing or canonical.startswith(missing + ".")):
            raise
        return import_module(legacy)


def __getattr__(name: str) -> Any:
    try:
        canonical, legacy = _NAMES[name]
    except KeyError:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}") from None
    value = getattr(_import_first_available(canonical, legacy), name)
    globals()[name] = value
    return value


def __dir__():
    return __all__

