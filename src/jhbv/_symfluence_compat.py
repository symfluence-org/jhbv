"""Resolve SYMFLUENCE framework names across core releases.

SYMFLUENCE moved its shared modelling and calibration infrastructure under
``symfluence.core`` (ADR 0011, docs/adr/0011-retire-unused-back-compat-shims.md
in the SYMFLUENCE repository). The old module paths still import, but they emit
``DeprecationWarning`` and will be removed before SYMFLUENCE 1.0. The new paths,
however, do not exist in symfluence 0.9.2 and earlier, which this plugin still
supports.

Each name below is therefore imported from its canonical location first, and
from the legacy location only when the canonical module is missing. Lookups are
lazy (PEP 562), so importing a light name such as a config base class does not
pull in the calibration stack.

Drop the legacy fallbacks (and route imports straight to ``symfluence.core``)
once this plugin requires the first symfluence release after 0.9.2.
"""

